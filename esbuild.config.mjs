import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";
import builtins from "module";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

function loadEnvFile(envPath) {
	const env = {};
	if (!fs.existsSync(envPath)) return env;
	const lines = fs.readFileSync(envPath, "utf8").split(/\r?\n/);
	for (const rawLine of lines) {
		const line = rawLine.trim();
		if (!line || line.startsWith("#")) continue;
		const eqIdx = line.indexOf("=");
		if (eqIdx === -1) continue;
		const key = line.slice(0, eqIdx).trim();
		let val = line.slice(eqIdx + 1).trim();
		if (
			(val.startsWith('"') && val.endsWith('"')) ||
			(val.startsWith("'") && val.endsWith("'"))
		) {
			val = val.slice(1, -1);
		}
		env[key] = val;
	}
	return env;
}

function getSyncTargetDir() {
	const fileEnv = loadEnvFile(path.resolve(".env"));
	const pluginDir = process.env.OBSIDIAN_PLUGIN_DIR || fileEnv.OBSIDIAN_PLUGIN_DIR;
	if (pluginDir) return path.resolve(pluginDir);

	const vaultPath = process.env.OBSIDIAN_VAULT_PATH || fileEnv.OBSIDIAN_VAULT_PATH;
	if (!vaultPath) return null;

	const manifest = JSON.parse(fs.readFileSync(path.resolve("manifest.json"), "utf8"));
	return path.join(path.resolve(vaultPath), ".obsidian", "plugins", manifest.id);
}

function syncToVault() {
	const targetDir = getSyncTargetDir();
	if (!targetDir) return;

	fs.mkdirSync(targetDir, { recursive: true });
	const filesToCopy = ["main.js", "manifest.json", "styles.css"];
	for (const file of filesToCopy) {
		const src = path.resolve(file);
		if (fs.existsSync(src)) {
			fs.copyFileSync(src, path.join(targetDir, file));
		}
	}
	console.log(`[sync] Copied plugin files to: ${targetDir}`);
}

const syncPlugin = {
	name: "obsidian-vault-sync",
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length === 0) {
				syncToVault();
			}
		});
	},
};

const jsContext = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins.builtinModules,
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	plugins: [syncPlugin],
});

const cssContext = await esbuild.context({
	entryPoints: ["src/styles.css"],
	bundle: true,
	outfile: "styles.css",
	minify: prod,
	logLevel: "info",
	plugins: [syncPlugin],
});

if (prod) {
	await Promise.all([jsContext.rebuild(), cssContext.rebuild()]);
	process.exit(0);
} else {
	await Promise.all([jsContext.watch(), cssContext.watch()]);
	const target = getSyncTargetDir();
	if (!target) {
		console.log(
			"[sync] Tip: Set OBSIDIAN_VAULT_PATH in .env to auto-copy builds to your Obsidian vault."
		);
	}
}
